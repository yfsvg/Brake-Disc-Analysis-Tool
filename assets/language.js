/**
 * Updates text and placeholders across elements matching [data-i18n] and [data-i18n-placeholder]
 * @param {string} lang - Selected language code ('en', 'cn', 'de')
 */
function changeLanguage(lang) {
    if (!translations[lang]) return;

    // 1. Update general text content
    const elementsToTranslate = document.querySelectorAll('[data-i18n]');
    elementsToTranslate.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Handle special cases where elements contain dynamic child spans/nodes
            if (element.children.length === 0) {
                element.textContent = translations[lang][key];
            } else {
                // If element has text node directly before children, update first child text node
                const firstChild = element.childNodes[0];
                if (firstChild && firstChild.nodeType === Node.TEXT_NODE) {
                    firstChild.nodeValue = translations[lang][key] + ' ';
                } else {
                    element.textContent = translations[lang][key];
                }
            }
        }
    });

    // 2. Update element input placeholders
    const placeholdersToTranslate = document.querySelectorAll('[data-i18n-placeholder]');
    placeholdersToTranslate.forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }
    });

    // 3. Save selection preference in localStorage
    localStorage.setItem('selectedLanguage', lang);
}

// Automatically load stored language or default to English on startup
document.addEventListener('DOMContentLoaded', () => {
    const savedLanguage = localStorage.getItem('selectedLanguage') || 'en';
    const langSelect = document.getElementById('languageSelection');
    
    if (langSelect) {
        langSelect.value = savedLanguage;
    }
    
    changeLanguage(savedLanguage);
});